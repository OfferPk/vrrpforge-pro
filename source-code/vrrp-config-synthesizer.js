  function generateJunos(cfg) {
    const vrid = cfg.vrid || 1;
    const vlan = cfg.vlan || 100;
    const vip = cfg.vip || '10.0.0.254';
    const primaryIp = cfg.primaryIp || '10.0.0.1';
    const cidr = cfg.cidr || '24';
    const priority = cfg.masterPriority || 110;
    const adverMs = cfg.adverIntervalMs || 250;
    const preemptDelay = cfg.preemptDelaySec || 60;
    const wanIface = cfg.wanInterface || 'et-0/0/1';

    let out = [];
    out.push('# ==============================================================================');
    out.push('# Juniper Junos VRRPv3 Configuration (EX / QFX / MX Series)');
    out.push('# Generated by VRRPForge Pro v1.0.0');
    out.push('# ==============================================================================');
    out.push('');
    out.push(`set interfaces irb unit ${vlan} family inet address ${primaryIp}/${cidr} vrrp-group ${vrid} virtual-address ${vip}`);
    out.push(`set interfaces irb unit ${vlan} family inet address ${primaryIp}/${cidr} vrrp-group ${vrid} priority ${priority}`);
    out.push(`set interfaces irb unit ${vlan} family inet address ${primaryIp}/${cidr} vrrp-group ${vrid} advertise-interval ${Math.round(adverMs / 10)}`);
    if (cfg.preempt !== false) {
      out.push(`set interfaces irb unit ${vlan} family inet address ${primaryIp}/${cidr} vrrp-group ${vrid} preempt delay ${preemptDelay}`);
    }
    if (cfg.trackingEnabled) {
      out.push(`set interfaces irb unit ${vlan} family inet address ${primaryIp}/${cidr} vrrp-group ${vrid} track interface ${wanIface} priority-cost ${cfg.trackDecrement || 30}`);
    }
    out.push(`set interfaces irb unit ${vlan} family inet address ${primaryIp}/${cidr} vrrp-group ${vrid} accept-data`);
    out.push('');

    return out.join('\n');
  }

