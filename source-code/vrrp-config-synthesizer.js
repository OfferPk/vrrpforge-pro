    out.push(' no shutdown');
    out.push('!');

    if (cfg.l2SecurityEnabled) {
      out.push('! 4. Access Switch L2 Rogue Master Defense');
      out.push(`ip arp inspection vlan ${vlan}`);
      out.push(`ip dhcp snooping vlan ${vlan}`);
      out.push('!');
    }

