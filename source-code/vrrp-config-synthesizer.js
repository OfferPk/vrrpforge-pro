      out.push('!');
      out.push('class-map match-all CLASS-COPP-VRRP');
      out.push(' match access-group name ACL-COPP-VRRP');
      out.push('!');
      out.push('policy-map POLICY-COPP-SYSTEM');
      out.push(' class CLASS-COPP-VRRP');
      out.push('  police rate 1000 pps conform-action transmit exceed-action drop');
      out.push('!');
      out.push('control-plane');
      out.push(' service-policy input POLICY-COPP-SYSTEM');
